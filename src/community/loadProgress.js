// ------------------------------------------------------------------
// コミュニティタブの読み込みの進み具合。
//
// 【なぜ「本当の%」ではないのか ── 先に正直に書いておく】
// この待ち時間の実体は3つで、**どれも進捗を取り出せない**。
//   (a) lazy() の chunk 取得   … import() は「終わった/失敗した」しか返さない。
//       進捗を取るには同じものを fetch で二重に落とすしかなく、待ち時間が増える。
//   (b) 匿名アカウントの確認 + 自分のプロフィールの読み … Firestore の1往復。
//   (c) 名簿(公開ユーザー + 通報)の読み … Firestore の1往復。
// つまり「いま何バイト来たか」は原理的に分からない。ここで数えているのは
// **段階**で、段階と段階のあいだは**経過時間で内挿している**。
//
// 内挿は必ず「次の段階の値へ**漸近する**」形にする(1 - e^(-t/τ))。
//   ・止まって見えない ── 遅い端末ほど長く、細かく動き続ける。
//   ・**追い越さない** ── 何秒待とうと次の段階の値を超えないので、
//     「95% まで行ったのに 40% へ戻る」が起きない。数字は単調に増える。
//   ・99 で頭打ちにする。100% は「終わった」の意味なので、まだ待っている
//     あいだは出さない(終わった瞬間にこの画面ごと消える)。
//
// 【段階は「その回に通る道」だけで割る】2回目に開いたときは chunk が
// ブラウザに残っていて Suspense の待ちが**そもそも出ない**。1回目と同じ
// 重みで割ると、2回目はいきなり 45% から始まってしまう。beginLoad は
// 呼ばれた段階から後ろだけで 100% を割り直す。
// ------------------------------------------------------------------

// 重みは「体感でどれくらい待つか」の目安。合計は割り算で正規化するので
// ここが 100 である必要はない。chunk が重いのは firebase を連れてくるから。
const STEPS = [
  { key: "chunk", weight: 45 },   // 画面のコードを取ってくる(App.jsx の Suspense)
  { key: "account", weight: 35 }, // 端末の匿名アカウント + 自分のプロフィール
  { key: "list", weight: 20 },    // 公開ユーザーの名簿と通報の一覧
];

// 内挿の時定数。**これは見た目の曲線ではなく「1往復にかかる時間」の見積り**なので、
// index.css ではなくここに置く(§1.11 が index.css に集めているのは
// アニメーションの秒数と曲線で、CSS 側に等価な書き方が無いものは対象外)。
// 900ms は「τ で 63%、2τ=1.8秒で 86% まで来る」の意味。実測の1往復が
// おおよそこの程度なので、速い回線では段階の頭で数字が跳ね、遅い回線では
// ゆっくり詰めていく ── どちらも嘘をつかない。
const TAU_MS = 900;

// 進行中の1回ぶん。null は「まだ何も始まっていない」。
// module のトップに置くのは、**3つの読み込み画面がそれぞれ別の要素**だから。
// Suspense の fallback → CommunityTabBody の loading → 名簿の loading と
// 入れ替わるたびに React の state なら 0 に戻ってしまい、数字が巻き戻る。
let plan = null;

const idxOf = (key) => STEPS.findIndex((s) => s.key === key);

// この段階が始まった、と伝える。**終わりは伝えなくてよい** ── 次の段階が
// 始まったことが、前の段階が終わった証拠だから。呼ぶ場所が減るぶん、
// 「終わりを呼び忘れて 40% で止まる」が起きない。
export function beginLoad(key, now = Date.now()) {
  const i = idxOf(key);
  if (i < 0) return;
  // 【前の段階が始まったときだけ割り直す】「同じ段階がもう一度」で割り直しては
  // いけない ── React の StrictMode は開発時に effect を**わざと2回**走らせるので、
  // beginLoad("account") が2回来て 45% → 0% と巻き戻る(要素の作り直しでも同じ)。
  // 前の段階が始まったのなら、それは間違いなく別の回。
  //
  // 副作用として、前の回が account で終わった人(未参加のまま去った人)が開き直すと
  // 45% から始まる。数字は前へしか進まないし、**実際その回は速い**(chunk も
  // アカウントの確認も端末に残っている)ので、0 から始めるより実態に近い。
  if (!plan || i < plan.i) {
    const rest = STEPS.slice(i);
    plan = {
      i,
      total: rest.reduce((a, s) => a + s.weight, 0),
      done: 0,
      since: now,
    };
    return;
  }
  // 同じ段階の入り直しは**何もしない**。since を今に書き直すだけでも
  // 内挿がその段階の頭へ戻り、数字が巻き戻る(51% → 45%)。
  if (i === plan.i) return;
  // 飛ばされた段階も終わったものとして足す(未参加の人は list を通らない等)。
  for (let k = plan.i; k < i; k++) plan.done += STEPS[k].weight;
  plan.i = i;
  plan.since = now;
}

// いまの段階の入口の値(%)。動きを減らす設定の端末はこれだけを出す。
export function loadFloor() {
  if (!plan) return 0;
  return (plan.done / plan.total) * 100;
}

export function loadPercent(now = Date.now()) {
  if (!plan) return 0;
  const base = loadFloor();
  const span = (STEPS[plan.i].weight / plan.total) * 100;
  const t = 1 - Math.exp(-Math.max(0, now - plan.since) / TAU_MS);
  return Math.min(99, base + span * t);
}

// 検査用。本体からは呼ばない(呼ぶと数字が巻き戻る)。
export function resetLoadProgress() { plan = null; }

// ------------------------------------------------------------------
// ficus の育ち方。0 → 1 で**鉢から幹が伸び、伸びた先で葉の房が開く**。
//
// 【姿は本人の株そのもの 2026/09/10 本人指示】写真で指定された曲げ仕立ての
// フィカス・ベンガレンシス。白い鉢・うねる淡色の幹・濃い葉の房が4段。
// 「ロードが進むたびにこの巻いている幹が伸びていくイメージ」がそのまま
// 進行の骨格になっている ── 幹の伸びが1本の数で決まり、房はその**先端が
// 通り過ぎた所から**開くので、絵の全部が1つの進捗に結ばれる。
//
// 【なぜ時間ではなく進捗で育てるか】時間で育てると、遅い端末では育ちきった
// あとも待たされ、速い端末では芽のまま消える。進捗に結ぶと**幹の長さが
// そのまま残りの量**になり、数字を読まなくても分かる。
//
// 【ここが持つのは順番だけ】どの高さに房があるか・房に葉が何枚あるかは
// 絵の話なので LoadingFicus.jsx が持つ。こちらは「鉢 → 幹 → 房1..4」の
// 進み方だけを決める。
// ------------------------------------------------------------------

const seg = (p, a, b) => Math.min(1, Math.max(0, (p - a) / (b - a)));

// 房が開き始める位置。幹の先端がその高さを通り過ぎた直後に来るよう選んである
// (幹は 0.04→0.72 で伸びるので、0.26 のとき先端は 3割、0.74 で伸びきる)。
// 最後の房が開き終わるのは **0.99** ── %が 99 で頭打ちだから(上を見ること)。
// 1.0 に合わせると、実際に出しうる最大でも株が完成しない。
const TIER_STARTS = [0.26, 0.42, 0.58, 0.74];
const BRANCH_SPAN = 0.05; // 枝が伸びる長さ
const LEAF_SPAN = 0.21;   // 房が開ききるまで

export function ficusGrowth(p) {
  const q = Math.min(1, Math.max(0, p || 0));
  return {
    // 鉢は**最初から見えている**。0 から出すと、読み込み画面が現れた瞬間に
    // 何も無い空白が出る。薄く置いてすぐ濃くなるだけにする。
    pot: 0.45 + 0.55 * seg(q, 0, 0.05),
    // うねる幹。dasharray で根元から先端へ伸ばす。
    trunk: seg(q, 0.04, 0.72),
    tiers: TIER_STARTS.map((s) => ({
      branch: seg(q, s, s + BRANCH_SPAN),
      // 房ぜんたいの開き具合(0〜1)。房の中で葉を1枚ずつずらすのは絵の側の仕事。
      leaves: seg(q, s + 0.04, s + 0.04 + LEAF_SPAN),
    })),
  };
}
